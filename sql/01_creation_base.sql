SET client_min_messages = warning;   -- pas de NOTICE au rechargement

DROP TABLE IF EXISTS reservation, emprunt, exemplaire, ecrire, livre,
    emplacement, categorie, editeur, auteur, bibliothecaire, adherent,
    personne CASCADE;
DROP TYPE IF EXISTS type_adherent_enum, etat_exemplaire_enum,
    statut_reservation_enum, statut_amende_enum CASCADE;
DROP FUNCTION IF EXISTS fn_exclusivite_role(), fn_personne_totale(),
    fn_livre_a_un_auteur() CASCADE;

-- ---------------------------------------------------------------------
--  1. Types énumérés
-- ---------------------------------------------------------------------
CREATE TYPE type_adherent_enum      AS ENUM ('etudiant', 'enseignant');
CREATE TYPE etat_exemplaire_enum    AS ENUM ('bon', 'abime', 'perdu');
CREATE TYPE statut_reservation_enum AS ENUM ('en_attente', 'recupere', 'annule');
CREATE TYPE statut_amende_enum      AS ENUM ('aucune', 'impayee', 'payee', 'annulee');

-- ---------------------------------------------------------------------
--  2. Tables
--  Les identifiants sont GENERATED BY DEFAULT AS IDENTITY : la base les
--  génère seule (site web, serveur Java) mais on peut en imposer un
--  explicitement (jeu de données initial).
-- ---------------------------------------------------------------------

-- Super-type de l'héritage
CREATE TABLE personne (
    id_personne           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom                   VARCHAR(50)  NOT NULL,
    prenom                VARCHAR(50)  NOT NULL,
    email                 VARCHAR(100) NOT NULL UNIQUE,
    date_naissance        DATE         NOT NULL,
    identifiant_connexion VARCHAR(50)  NOT NULL UNIQUE,
    mot_de_passe_hache    VARCHAR(255) NOT NULL,

    CONSTRAINT ck_personne_id        CHECK (id_personne >= 0),
    CONSTRAINT ck_personne_nom       CHECK (char_length(trim(nom)) >= 2
                                            AND nom !~ '[0-9]'),
    CONSTRAINT ck_personne_prenom    CHECK (char_length(trim(prenom)) >= 2
                                            AND prenom !~ '[0-9]'),
    CONSTRAINT ck_personne_email     CHECK (email ~ '^[^@[:space:]]+@[^@[:space:]]+[.][^@[:space:]]+$'),
    CONSTRAINT ck_personne_naissance CHECK (date_naissance >= DATE '1900-01-01'
                                            AND date_naissance < CURRENT_DATE),
    CONSTRAINT ck_personne_login     CHECK (char_length(identifiant_connexion) >= 3),
    CONSTRAINT ck_personne_mdp       CHECK (char_length(mot_de_passe_hache) >= 60)
);

-- Sous-type 1
CREATE TABLE adherent (
    id_adherent      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_personne      INT  NOT NULL UNIQUE REFERENCES personne(id_personne),
    date_inscription DATE NOT NULL DEFAULT CURRENT_DATE,
    actif_adherent   BOOLEAN NOT NULL DEFAULT TRUE,
    type_adherent    type_adherent_enum NOT NULL,

    CONSTRAINT ck_adherent_id          CHECK (id_adherent >= 0),
    CONSTRAINT ck_adherent_inscription CHECK (date_inscription <= CURRENT_DATE)
);

-- Sous-type 2
CREATE TABLE bibliothecaire (
    id_bibliothecaire INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_personne       INT  NOT NULL UNIQUE REFERENCES personne(id_personne),
    date_embauche     DATE NOT NULL,
    fonction          VARCHAR(50) NOT NULL,

    CONSTRAINT ck_biblio_id       CHECK (id_bibliothecaire >= 0),
    CONSTRAINT ck_biblio_embauche CHECK (date_embauche <= CURRENT_DATE),
    CONSTRAINT ck_biblio_fonction CHECK (char_length(trim(fonction)) >= 2)
);

CREATE TABLE auteur (
    id_auteur     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom_auteur    VARCHAR(50) NOT NULL,
    prenom_auteur VARCHAR(50),

    CONSTRAINT ck_auteur_id     CHECK (id_auteur >= 0),
    CONSTRAINT ck_auteur_nom    CHECK (char_length(trim(nom_auteur)) >= 2),
    CONSTRAINT ck_auteur_prenom CHECK (char_length(trim(prenom_auteur)) >= 2)
);

CREATE TABLE editeur (
    id_editeur  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom_editeur VARCHAR(100) NOT NULL,

    CONSTRAINT ck_editeur_id  CHECK (id_editeur >= 0),
    CONSTRAINT ck_editeur_nom CHECK (char_length(trim(nom_editeur)) >= 2)
);

CREATE TABLE categorie (
    id_categorie      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle_categorie VARCHAR(50) NOT NULL UNIQUE,

    CONSTRAINT ck_categorie_id      CHECK (id_categorie >= 0),
    CONSTRAINT ck_categorie_libelle CHECK (char_length(trim(libelle_categorie)) >= 2)
);

CREATE TABLE emplacement (
    id_emplacement INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    salle          VARCHAR(30) NOT NULL,
    rayon          VARCHAR(30) NOT NULL,

    UNIQUE (salle, rayon),
    CONSTRAINT ck_emplacement_id    CHECK (id_emplacement >= 0),
    CONSTRAINT ck_emplacement_salle CHECK (char_length(trim(salle)) >= 1),
    CONSTRAINT ck_emplacement_rayon CHECK (char_length(trim(rayon)) >= 1)
);

CREATE TABLE livre (
    id_livre          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isbn              VARCHAR(13)  NOT NULL UNIQUE,
    titre_livre       VARCHAR(200) NOT NULL,
    langue_livre      VARCHAR(30)  NOT NULL,
    annee_publication INTEGER      NOT NULL,
    nombre_pages      INTEGER      NOT NULL,
    couverture_livre  BYTEA,                         -- image (BLOB), facultative
    id_editeur        INT NOT NULL REFERENCES editeur(id_editeur),     -- 1,1
    id_categorie      INT NOT NULL REFERENCES categorie(id_categorie), -- 1,1

    CONSTRAINT ck_livre_id      CHECK (id_livre >= 0),
    CONSTRAINT ck_livre_isbn    CHECK (isbn ~ '^97[89][0-9]{10}$'),
    CONSTRAINT ck_livre_titre   CHECK (char_length(trim(titre_livre)) >= 1),
    CONSTRAINT ck_livre_langue  CHECK (char_length(trim(langue_livre)) >= 2
                                       AND langue_livre !~ '[0-9]'),
    CONSTRAINT ck_livre_annee   CHECK (annee_publication BETWEEN 1450
                                       AND EXTRACT(YEAR FROM CURRENT_DATE)),
    CONSTRAINT ck_livre_pages   CHECK (nombre_pages BETWEEN 1 AND 10000),
    CONSTRAINT ck_livre_couv    CHECK (couverture_livre IS NULL
                                       OR octet_length(couverture_livre) <= 5 * 1024 * 1024)
);

-- Association N-N livre <-> auteur
CREATE TABLE ecrire (
    id_livre  INT NOT NULL REFERENCES livre(id_livre),
    id_auteur INT NOT NULL REFERENCES auteur(id_auteur),
    PRIMARY KEY (id_livre, id_auteur)
);

CREATE TABLE exemplaire (
    id_exemplaire  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_inventaire VARCHAR(20) NOT NULL UNIQUE,
    etat_exemplaire etat_exemplaire_enum NOT NULL DEFAULT 'bon',
    id_livre        INT NOT NULL REFERENCES livre(id_livre),             -- 1,1
    id_emplacement  INT NOT NULL REFERENCES emplacement(id_emplacement), -- 1,1

    CONSTRAINT ck_exemplaire_id   CHECK (id_exemplaire >= 0),
    CONSTRAINT ck_exemplaire_code CHECK (code_inventaire ~ '^EX[0-9]{3,}$')
);

CREATE TABLE emprunt (
    id_emprunt         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_emprunt       DATE NOT NULL DEFAULT CURRENT_DATE,
    date_retour_prevue DATE NOT NULL,
    date_retour_effective DATE,
    montant_amende     DECIMAL(6,2) NOT NULL DEFAULT 0,
    date_emission      DATE,
    date_paiement      DATE,
    statut_amende      statut_amende_enum NOT NULL DEFAULT 'aucune',
    id_adherent        INT NOT NULL REFERENCES adherent(id_adherent),               -- 1,1
    id_bibliothecaire  INT NOT NULL REFERENCES bibliothecaire(id_bibliothecaire),   -- 1,1
    id_exemplaire      INT NOT NULL REFERENCES exemplaire(id_exemplaire),           -- 1,1

    CONSTRAINT ck_emprunt_id      CHECK (id_emprunt >= 0),
    CONSTRAINT ck_emprunt_date    CHECK (date_emprunt <= CURRENT_DATE),
    CONSTRAINT ck_emprunt_duree   CHECK (date_retour_prevue = date_emprunt + 14),
    CONSTRAINT ck_emprunt_retour  CHECK (date_retour_effective IS NULL
                                         OR (date_retour_effective >= date_emprunt
                                             AND date_retour_effective <= CURRENT_DATE)),
    CONSTRAINT ck_emprunt_montant CHECK (montant_amende >= 0),
    CONSTRAINT ck_emprunt_emission CHECK (date_emission IS NULL OR date_emission <= CURRENT_DATE),
    CONSTRAINT ck_emprunt_paiement CHECK (date_paiement IS NULL
                                          OR (date_emission IS NOT NULL
                                              AND date_paiement >= date_emission
                                              AND date_paiement <= CURRENT_DATE)),
    CONSTRAINT ck_emprunt_aucune  CHECK (statut_amende <> 'aucune'
                                         OR (montant_amende = 0
                                             AND date_emission IS NULL
                                             AND date_paiement IS NULL)),
    CONSTRAINT ck_emprunt_impayee CHECK (statut_amende <> 'impayee'
                                         OR (montant_amende > 0
                                             AND date_emission IS NOT NULL
                                             AND date_paiement IS NULL)),
    CONSTRAINT ck_emprunt_payee   CHECK (statut_amende <> 'payee'
                                         OR (montant_amende > 0
                                             AND date_emission IS NOT NULL
                                             AND date_paiement IS NOT NULL))
);

CREATE TABLE reservation (
    id_reservation     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_reservation   DATE NOT NULL DEFAULT CURRENT_DATE,
    statut_reservation statut_reservation_enum NOT NULL DEFAULT 'en_attente',
    id_adherent        INT NOT NULL REFERENCES adherent(id_adherent), -- 1,1
    id_livre           INT NOT NULL REFERENCES livre(id_livre),       -- 1,1

    CONSTRAINT ck_reservation_id   CHECK (id_reservation >= 0),
    CONSTRAINT ck_reservation_date CHECK (date_reservation <= CURRENT_DATE)
);

-- ---------------------------------------------------------------------
--  3. Règles métier garanties par la base
-- ---------------------------------------------------------------------

-- Un exemplaire ne peut avoir qu'UN SEUL emprunt en cours (retour non effectué).
-- Protège aussi contre deux prêts simultanés du même exemplaire.
CREATE UNIQUE INDEX ux_emprunt_exemplaire_en_cours
    ON emprunt (id_exemplaire) WHERE date_retour_effective IS NULL;

-- Un adhérent ne peut avoir qu'UNE réservation en attente par livre.
CREATE UNIQUE INDEX ux_reservation_en_attente
    ON reservation (id_adherent, id_livre) WHERE statut_reservation = 'en_attente';

-- Accélère la recherche des emprunts d'un adhérent / des réservations d'un livre.
CREATE INDEX ix_emprunt_adherent    ON emprunt (id_adherent);
CREATE INDEX ix_reservation_livre   ON reservation (id_livre);

-- Héritage EXCLUSIF : une personne ne peut pas être adhérent ET bibliothécaire.
CREATE FUNCTION fn_exclusivite_role() RETURNS trigger AS $$
BEGIN
    IF TG_TABLE_NAME = 'adherent'
       AND EXISTS (SELECT 1 FROM bibliothecaire WHERE id_personne = NEW.id_personne) THEN
        RAISE EXCEPTION 'La personne % est déjà bibliothécaire', NEW.id_personne
              USING ERRCODE = 'check_violation';
    ELSIF TG_TABLE_NAME = 'bibliothecaire'
       AND EXISTS (SELECT 1 FROM adherent WHERE id_personne = NEW.id_personne) THEN
        RAISE EXCEPTION 'La personne % est déjà adhérent', NEW.id_personne
              USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER trg_adherent_exclusif
    BEFORE INSERT OR UPDATE OF id_personne ON adherent
    FOR EACH ROW EXECUTE FUNCTION fn_exclusivite_role();
CREATE TRIGGER trg_biblio_exclusif
    BEFORE INSERT OR UPDATE OF id_personne ON bibliothecaire
    FOR EACH ROW EXECUTE FUNCTION fn_exclusivite_role();

-- Héritage TOTAL : toute personne est adhérent OU bibliothécaire
-- (vérifié à la fin de la transaction : insérer personne + rôle dans la même transaction).
CREATE FUNCTION fn_personne_totale() RETURNS trigger AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM adherent WHERE id_personne = NEW.id_personne)
       AND NOT EXISTS (SELECT 1 FROM bibliothecaire WHERE id_personne = NEW.id_personne) THEN
        RAISE EXCEPTION 'La personne % doit être adhérent ou bibliothécaire', NEW.id_personne
              USING ERRCODE = 'check_violation';
    END IF;
    RETURN NULL;
END $$ LANGUAGE plpgsql;

CREATE CONSTRAINT TRIGGER trg_personne_totale
    AFTER INSERT ON personne
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION fn_personne_totale();

-- Association ECRIRE : cardinalité 1,N côté livre (au moins un auteur par livre).
CREATE FUNCTION fn_livre_a_un_auteur() RETURNS trigger AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM ecrire WHERE id_livre = NEW.id_livre) THEN
        RAISE EXCEPTION 'Le livre % doit avoir au moins un auteur', NEW.id_livre
              USING ERRCODE = 'check_violation';
    END IF;
    RETURN NULL;
END $$ LANGUAGE plpgsql;

CREATE CONSTRAINT TRIGGER trg_livre_auteur
    AFTER INSERT ON livre
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION fn_livre_a_un_auteur();

